#!/usr/bin/env python3
"""Fetch the SimpleSvm source and rewrite its C++ spellings to C99.

SimpleSvm is Satoshi Tanda's small AMD-SVM hypervisor, built upstream as
a Windows kernel driver in C-style C++ (one SimpleSvm.cpp, one
SimpleSvm.hpp, one MASM module). badc is a C compiler, so this demo
compiles the driver's logic as C99: the handful of C++-only spellings in
the source (the two cast operators, nullptr and constexpr) are rewritten
here, the WDK/intrinsic surface is supplied by the demo-local headers in
include/, the MASM module is translated to a badc naked function in
x64_asm.c, and the result links into a native-subsystem .sys.

After this runs, ``demos/simplesvm/src/{SimpleSvm.c, SimpleSvm.hpp}``
exist alongside those demo-local files.

The rewrite is deterministic and auditable; it does not touch control
flow, types or logic:

  * ``reinterpret_cast<T>`` / ``static_cast<T>``  ->  ``(T)``
  * ``nullptr``                                   ->  ``NULL``
  * ``constexpr``                                 ->  ``const``
  * ``#pragma prefast(...)`` lines (MSVC static-analysis directives with
    no codegen effect) are dropped.

EXTERN_C and static_assert are left in place; include/svcompat.h maps
them to their C spellings.

Pulls the pinned upstream archive from the badc vendor-deps mirror,
falling back to github.com/tandasat/SimpleSvm; ``_fetch`` verifies the
sha256 of whichever bytes arrive. See ``scripts/vendor_deps/README.md``
for the auth model. Idempotent: safe to call from CI before each smoke
run. Output is suppressed unless something fails -- pass ``-v`` to see
every step.
"""

from __future__ import annotations

import argparse
import re
import sys
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts" / "vendor_deps"))
import _fetch  # noqa: E402

VERSION = "20250303"
UPSTREAM_SHA = "c4a479e0244b5771c0c865f751f97d1b4f27c091"  # github.com/tandasat/SimpleSvm HEAD
ASSET = f"simplesvm-{VERSION}-{UPSTREAM_SHA[:8]}.zip"
RELEASE_TAG = "vendor-deps-v1"
SHA256 = "37e30132d7259d9a966b96d49e590e6f178702a15f9d9bd40072c501f224c31c"
FALLBACK_URL = f"https://github.com/tandasat/SimpleSvm/archive/{UPSTREAM_SHA}.zip"

_CAST_RE = re.compile(r"\b(?:reinterpret|static)_cast\s*<\s*([^<>]+?)\s*>")
_PREFAST_RE = re.compile(r"^[ \t]*#pragma[ \t]+prefast\b.*(?:\r?\n)?", re.MULTILINE)


def cpp_to_c99(text: str) -> str:
    """Rewrite the C++-only spellings SimpleSvm.cpp uses into C99."""
    text = _CAST_RE.sub(r"(\1)", text)
    text = re.sub(r"\bnullptr\b", "NULL", text)
    text = re.sub(r"\bconstexpr\b", "const", text)
    text = _PREFAST_RE.sub("", text)
    return text


GENERATED_BANNER = (
    "/* Generated by demos/simplesvm/setup.py from SimpleSvm {sha} -- do not\n"
    " * edit by hand. The C++ spellings of the upstream SimpleSvm.cpp have\n"
    " * been rewritten to C99 (casts, nullptr, constexpr); nothing else is\n"
    " * changed. Upstream is MIT-licensed, Copyright (c) 2017-2020 Satoshi\n"
    " * Tanda. */\n"
).format(sha=UPSTREAM_SHA[:8])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    def log(msg: str) -> None:
        if args.verbose:
            print(msg, file=sys.stderr)

    demo_dir = Path(__file__).resolve().parent
    cache_dir = demo_dir / ".cache"
    src_dir = demo_dir / "src"
    zip_path = cache_dir / ASSET

    cache_dir.mkdir(parents=True, exist_ok=True)
    src_dir.mkdir(parents=True, exist_ok=True)
    _fetch.fetch_and_verify(RELEASE_TAG, ASSET, zip_path, SHA256, log, FALLBACK_URL)

    log("extracting and rewriting SimpleSvm")
    prefix = f"SimpleSvm-{UPSTREAM_SHA}/SimpleSvm"
    with zipfile.ZipFile(zip_path) as zf:
        cpp = zf.read(f"{prefix}/SimpleSvm.cpp").decode("utf-8")
        hpp = zf.read(f"{prefix}/SimpleSvm.hpp").decode("utf-8")

    (src_dir / "SimpleSvm.c").write_text(GENERATED_BANNER + cpp_to_c99(cpp), encoding="utf-8")
    (src_dir / "SimpleSvm.hpp").write_text(hpp, encoding="utf-8")

    if args.verbose:
        for name in ("SimpleSvm.c", "SimpleSvm.hpp"):
            p = src_dir / name
            log(f"done -- {p} {p.stat().st_size}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
