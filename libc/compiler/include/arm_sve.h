/* The Arm C Language Extensions' <arm_sve.h> on AArch64: the sizeless SVE
 * vector and predicate types over the builtin type names, and the
 * intrinsics as calls of the compiler's rows (`__builtin_sve_<op>`), whose
 * first operand, where the row family has one, is the SVE type that
 * selects the row. The overloaded forms pass `void`, the builtin then
 * taking the type of its first SVE operand after the governing one, so
 * each macro names an operand once; a scalar where a vector operand stands
 * is that vector with the scalar in every lane, which serves the `_n`
 * forms. svcmplt and svcmple are svcmpgt
 * and svcmpge with the operands swapped. A family's svbool_t form, such as
 * svand_b_z, takes svbool_t as its type.
 *
 * Provided: svptrue, svptrue_pat, svcntb/h/w/d and their _pat forms,
 * svwhilelt, svld1, svst1, svadd, svsub, svmul, svdiv, svmin, svmax,
 * svminnm, svmaxnm, svabd, svmulh, svmla, svmls, svmad and svmsb, and
 * over the floating types svnmla, svnmls, svnmad and svnmsb, fused, and
 * svlsl, svlsr and svasr, whose
 * shift count is unsigned (_m, _z, _x, and _n), svqadd and svqsub (and
 * _n), svand, svorr, sveor and svbic (_m, _z, _x, _n, and _b_z), svorn,
 * svnand and svnor (_b_z), svnot (_m, _z, _x, and _b_z), svabs, svneg
 * and svsqrt (_m, _z, _x), svsel, svcmpeq, svcmpne,
 * svcmpgt, svcmpge, svcmplt, svcmple (and _n), the reductions svaddv,
 * svmaxv, svminv, svmaxnmv, svminnmv, svandv, svorv and sveorv, svdup_n,
 * svdup_lane, svreinterpret, the permutes svzip1, svzip2, svuzp1, svuzp2,
 * svtrn1, svtrn2, svrev and svext, and svptest_any/first/last, over the 8-
 * to 64-bit integer and the 32- and 64-bit floating element types. */
